"""Request/response models (they also drive the Swagger UI at /docs)."""

from __future__ import annotations

from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


class PredictRequest(BaseModel):
    csi_amplitude: list[list[float]] = Field(
        ..., description="Raw CSI amplitude window: 200 packets (2 s at 100 packets/s) x 52 subcarriers. "
                         "Get a ready-made example from GET /demo/sample-window.")
    fs: int = Field(100, description="Packet rate of the window (packets/s)")


class PredictResponse(BaseModel):
    predicted_class: str
    probabilities: dict[str, float]
    fall_probability: float
    fall_alert: bool
    threshold: float
    model_version: str
    latency_ms: float


class EventIn(BaseModel):
    event_id: str = Field(..., description="Unique id generated by the node (used for de-duplication)")
    node_id: str = Field(..., examples=["node-hh001-a"])
    type: Literal["fall", "motion_summary", "bathroom_enter", "bathroom_exit", "heartbeat"]
    ts: datetime | None = Field(None, description="Event time (ISO 8601). Defaults to now.")
    confidence: float | None = Field(None, ge=0, le=1, description="Model confidence for fall events")
    energy: float | None = Field(None, description="Motion energy for motion_summary events")


class EventOut(BaseModel):
    accepted: bool
    duplicate: bool = False
    event_id: int | None = None
    alert_id: int | None = None


class PersonIn(BaseModel):
    role: Literal["elder", "caregiver", "chw"]
    name: str
    phone: str | None = None
    language: Literal["rw", "en"] = "rw"


class PersonOut(PersonIn):
    model_config = ConfigDict(from_attributes=True)
    id: int


class NodeIn(BaseModel):
    id: str
    zone: Literal["living_room", "bathroom"] = "living_room"


class NodeOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: str
    zone: str
    status: str
    last_seen: datetime | None
    adapter_version: str


class HouseholdIn(BaseModel):
    id: str = Field(..., examples=["HH-004"])
    name: str
    cell: str = ""
    village: str = ""
    people: list[PersonIn] = []
    nodes: list[NodeIn] = []


class HouseholdOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: str
    name: str
    sector: str
    cell: str
    village: str
    people: list[PersonOut]
    nodes: list[NodeOut]


class HouseholdSummary(BaseModel):
    id: str
    name: str
    village: str
    elder: str | None
    open_alerts: int
    nodes_online: int
    nodes_total: int
    last_alert_at: datetime | None


class AlertOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: int
    household_id: str
    type: str
    severity: str
    status: str
    confidence: float | None
    created_at: datetime
    escalated_at: datetime | None
    ack_at: datetime | None
    ack_by: str | None
    ack_outcome: str | None
    details: dict


class AckIn(BaseModel):
    outcome: Literal["confirmed", "false_alarm"] = Field(..., description="confirmed = real fall/needed help")
    by: str = Field("dashboard", description="Who acknowledged (name or role)")


class SmsOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: int
    alert_id: int | None
    household_id: str | None
    direction: str
    phone: str
    recipient_role: str | None
    message: str
    status: str
    created_at: datetime


class NightOut(BaseModel):
    night: str
    restless_minutes: int
    baseline_mean: float | None
    baseline_std: float | None
    z_score: float | None
    flagged: bool
